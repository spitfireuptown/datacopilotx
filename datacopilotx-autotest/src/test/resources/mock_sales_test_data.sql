-- 智能问数系统（Text-to-SQL）批量测试专用标准数仓模型
-- 包含：门店维度表(dims_shop)、商品维度表(dims_product)、销售事实表(facts_sales)
-- ====================================================================

SET FOREIGN_KEY_CHECKS = 0;

-- 1. 创建门店维度表
DROP TABLE IF EXISTS `dims_shop`;
CREATE TABLE `dims_shop` (
  `shop_id` varchar(20) NOT NULL COMMENT '门店唯一编码',
  `shop_name` varchar(100) NOT NULL COMMENT '门店全称',
  `region` varchar(50) NOT NULL COMMENT '所属大区（如：华东、华北、华南、西南）',
  `city` varchar(50) NOT NULL COMMENT '所在城市',
  `manager` varchar(50) DEFAULT NULL COMMENT '门店店长姓名',
  PRIMARY KEY (`shop_id`),
  KEY `idx_region` (`region`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='门店维度表';

-- 2. 创建商品维度表
DROP TABLE IF EXISTS `dims_product`;
CREATE TABLE `dims_product` (
  `product_id` varchar(20) NOT NULL COMMENT '商品唯一编码',
  `product_name` varchar(200) NOT NULL COMMENT '商品名称',
  `category` varchar(50) NOT NULL COMMENT '一级品类',
  `subcategory` varchar(50) NOT NULL COMMENT '二级品类',
  `price` decimal(10,2) NOT NULL COMMENT '标准零售单价',
  `cost` decimal(10,2) NOT NULL COMMENT '商品进货成本',
  PRIMARY KEY (`product_id`),
  KEY `idx_category` (`category`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='商品维度表';

-- 3. 创建销售事实表
DROP TABLE IF EXISTS `facts_sales`;
CREATE TABLE `facts_sales` (
  `id` int(11) NOT NULL AUTO_INCREMENT COMMENT '自增主键',
  `order_id` varchar(30) NOT NULL COMMENT '订单全局唯一流水号',
  `shop_id` varchar(20) NOT NULL COMMENT '门店编码（关联dims_shop）',
  `product_id` varchar(20) NOT NULL COMMENT '商品编码（关联dims_product）',
  `sale_time` datetime NOT NULL COMMENT '销售交易时间',
  `quantity` int(11) NOT NULL COMMENT '销售数量',
  `price` decimal(10,2) NOT NULL COMMENT '单价(购买时单价)',
  `discount_amount` decimal(10,2) DEFAULT '0.00' COMMENT '优惠/折扣金额',
  `total_amount` decimal(10,2) NOT NULL COMMENT '最终实付总金额(price*quantity - discount)',
  PRIMARY KEY (`id`),
  KEY `idx_sale_time` (`sale_time`),
  KEY `idx_shop_id` (`shop_id`),
  KEY `idx_product_id` (`product_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='销售交易事实表';

